import {expect,test} from '@playwright/test';
import {readFile} from 'node:fs/promises';
import {LATEST_RELEASE} from '../../src/lib/releases';
test.beforeEach(async({page})=>{
 await page.addInitScript(release=>localStorage.setItem('parma.release-notes.seen',release),LATEST_RELEASE.id);
 await page.route('**/api/supabase/**',route=>route.abort());
});
test('home and character tabs have independent content, active state and mobile layout',async({page})=>{
 await page.setViewportSize({width:390,height:844});
 await page.goto('/');
 const nav=page.getByRole('navigation',{name:'Основная навигация'});
 await expect(nav.getByRole('link',{name:'Главная',exact:true})).toHaveAttribute('aria-current','page');
 await expect(nav.getByRole('link',{name:'Персонажи',exact:true})).not.toHaveAttribute('aria-current','page');
 await expect(page.getByRole('heading',{name:'С чего начать',exact:true})).toBeVisible();
 const updates=page.locator('section[aria-labelledby="updates-title"]');
 await expect(updates).toContainText(LATEST_RELEASE.title);
 await expect(updates.locator('li')).toHaveCount(Math.min(3,LATEST_RELEASE.changes.length));
 await expect(page.getByRole('link',{name:'Гайд Сказителя',exact:true})).toHaveAttribute('href','/learn?topic=storyteller');
 await expect(page.getByRole('heading',{name:'Ваши персонажи',exact:false})).toHaveCount(0);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.getByRole('link',{name:'Полная история обновлений ↓'}).click();
 await expect(page.getByRole('button',{name:'История обновлений'})).toBeInViewport();
 await nav.getByRole('link',{name:'Персонажи',exact:true}).click();
 await expect(page).toHaveURL(/\/characters$/);
 await expect(nav.getByRole('link',{name:'Персонажи',exact:true})).toHaveAttribute('aria-current','page');
 await expect(nav.getByRole('link',{name:'Главная',exact:true})).not.toHaveAttribute('aria-current','page');
 await expect(page.getByRole('heading',{name:'Персонажи',exact:true})).toBeVisible();
 await expect(page.getByRole('heading',{name:'Последние обновления'})).toHaveCount(0);
 await expect(page.getByRole('link',{name:'Скачать пустой лист персонажа'})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
test('existing heroes can be searched, exported, deleted and imported on the character page',async({page})=>{
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto('/new');
 await page.getByRole('textbox',{name:'Имя персонажа'}).fill('Герой переноса');
 await page.getByRole('button',{name:'Сохранить персонажа',exact:true}).click();
 await expect(page).toHaveURL(/\/char\/[\da-f-]+$/);
 const id=new URL(page.url()).pathname.split('/').at(-1);
 await page.getByRole('link',{name:'← К списку',exact:true}).click();
 await expect(page).toHaveURL(/\/characters$/);
 const hero=page.getByRole('link',{name:/Герой переноса/});
 await expect(hero).toBeVisible();
 await page.getByRole('searchbox',{name:'Поиск по имени или расе'}).fill('нет такого героя');
 await expect(hero).toHaveCount(0);
 await page.getByRole('button',{name:'Сбросить поиск'}).click();
 await expect(hero).toBeVisible();
 const downloaded=page.waitForEvent('download');
 await page.getByRole('button',{name:'Скачать персонажа Герой переноса в JSON'}).click();
 const file=await downloaded;const path=(await file.path())!;
 const payload=JSON.parse(await readFile(path,'utf8'));
 expect(JSON.stringify(payload)).toContain('Герой переноса');
 await page.getByRole('button',{name:'Удалить персонажа Герой переноса',exact:true}).click();
 await page.getByRole('button',{name:'Удалить',exact:true}).click();
 await expect(hero).toHaveCount(0);
 page.on('dialog',dialog=>dialog.accept());
 await page.locator('input[type="file"]').setInputFiles(path);
 await expect(hero).toBeVisible();await expect(hero).toHaveAttribute('href','/char/'+id);
 await page.goto('/');await expect(page.getByRole('link',{name:/Герой переноса/})).toHaveCount(0);
 await page.goto('/characters');await expect(hero).toBeVisible();
 expect(errors).toEqual([]);
});