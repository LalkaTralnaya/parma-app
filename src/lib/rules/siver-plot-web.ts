export function createSiverStoryPlotWeb(): StoryPlotWeb {
	const nodes: PlotNode[] = npcSpecs.map(([slug, name, id, origin, inclinations]) => {
		const npc = ADVENTURES.find((adventure) => adventure.slug === slug)?.npcs.find((entry) => entry.name === name);
		if (!npc) throw new Error('Не найден персонаж сюжетной паутины «' + name + '».');
		return { id: 'siver:' + id, type: 'npc', name: npc.name, description: npc.role + '\n\n' + npc.motive, origin, inclinations };
	});
	const edges = connections.map((connection, index) => {
		const [from, to, label] = connection;
		const details: readonly string[] = connection;
		return {
			id: 'siver:edge:' + (index + 1),
			from: 'siver:' + from,
			to: 'siver:' + to,
			label,
			notes: details[3] ?? '',
			condition: details[4] ?? '',
			consequence: details[5] ?? ''
		};
	});
	return normalizeStoryPlotWeb({ version: 1, nodes: [...extraNodes, ...nodes], edges, templateIds: [SIVER_PLOT_TEMPLATE_ID] });
}

export function addSiverStoryPlotWeb(graph: StoryPlotWeb): StoryPlotWeb {
	return mergeStoryPlotTemplate(graph, createSiverStoryPlotWeb(), SIVER_PLOT_TEMPLATE_ID);
}

/** An intentionally cleared imported graph stays cleared on the next visit. */
export function prepareStoryPlotWeb(graph: StoryPlotWeb): StoryPlotWeb {
	if (graph.nodes.length || graph.edges.length || graph.templateIds?.length) return graph;
	return createSiverStoryPlotWeb();
}
