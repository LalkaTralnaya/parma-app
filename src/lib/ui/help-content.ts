export type HelpTopicId = keyof typeof content;
export const HELP_TOPICS = Object.fromEntries(Object.entries(content).map(([id, topic]) => [id, { ...topic, id }])) as Record<HelpTopicId, HelpTopic>;

export function helpContent(id: HelpTopicId, variant: "full" | "short" = "full"): HelpContent {
 const topic = HELP_TOPICS[id];
 const selected = variant === "short" ? topic.short ?? topic : topic;
 return { title: selected.title, text: selected.text, ...(selected.href ? { href: selected.href } : {}), ...(selected.link ? { link: selected.link } : {}) };
}
export function contextTip(id: HelpTopicId) { return { id, ...helpContent(id, "short") }; }

export function helpPractice(id: HelpTopicId): HelpPractice | undefined {
 const practice = HELP_TOPICS[id].practice;
 return practice ? { ...practice, steps: [...practice.steps] } : undefined;
}
