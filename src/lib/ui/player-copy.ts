/** Present game content without source-file, migration, or editorial annotations. */
export function playerText(value: string): string {
 return value
  .replace(/^\s*Основание:[^\n]*(?:\n|$)/gmu, '')
  .replace(/\s+Основание:[^\n]*/gu, '')
  .replace(/(?:Это меняет книжное отсутствие обычного урона|Это изменение эффекта, требующее авторской проверки|Для окончательной карточки нужно отдельно принять эту звуковую защиту|Двухручные версии и ограничение «Равновесия» предложены впервые|Статус: рабочий черновик|Техническая основа — боевое самбо|Это описание уклада вымышленного мира, а не современный технический стандарт)[^.]*\.\s*/gu, '')
  .replace(/^Рабочая редакция(?: для обсуждения| «[^\n]*»)?\.?$/u, '')
  .replace(/Рабочая редакция(?: для обсуждения| «[^.\n]*»)?\.\s*/gu, '')
  .replace(/Действующий вариант черновика:\s*/gu, 'Ударная серия: ')
  .replace(/В этой редакции добавлено явное требование /gu, 'Требуется ')
  .replace(/В этой редакции 35 деревьев и 457 покупаемых узлов:[^.]*\.\s*/gu, '')
  .replace(/Для этой редакции он ограничивается /gu, 'Эффект ограничивается ')
  .replace(/(?:В книге есть три разные формулировки Обморожения|В книге одновременно написаны «урон нельзя уменьшить»)[^.]*\.\s*/gu, '')
  .replace(/(?:Это предлагаемое разрешение расхождения|Это предложенное ограничение повторного контроля|Это предложенный единый порядок|Это явная перебалансировка абсолютной формулировки|Материалы остаются рабочей редакцией|Эти цены и двухручные варианты новые|Все рисунки в таблице предложены впервые|Ниже - реестр для включения в единую книгу|Условия заказа у городского мастера предложены|Местные имена ещё не составлены)[^.]*\.\s*/gu, '')
  .replace(/Для рабочей редакции принимается подробная карточка состояния как единый источник:\s*/gu, 'Обморожение: ')
  .replace(/Для рабочей редакции предлагается:\s*/gu, '')
  .replace(/Для рабочей редакции сохранена полная карточка:\s*/gu, '')
  .replace(/Книжная основа\s*\([^)]*\):\s*/gu, '')
  .replace(/Книжная основа:\s*/gu, '')
  .replace(/По выбору автора в приложении продолжение потоковых чар не требует нового к100; это заменяет соответствующий пункт черновика магии\./gu, 'Продолжение потоковых чар не требует нового к100.')
  .replace(/Сочетание плоти с защитными оберегами Восстановления будет определено при переработке оберегов; их эффекты здесь не отменены и не разрешены к неограниченному сложению\./gu, 'Эффекты плоти и защитных оберегов Восстановления не отменены и не разрешены к неограниченному сложению.')
  .replace(/Как именно начисляются стихийные прибавки и скидки, будет определено следующими блоками переработки\./gu, '')
  .replace(/Отменяются прежние общие эффекты этих пяти узлов: дополнительный кубик, удвоение длительности и надбавка \+1 Живы\. Книжное усиление не складывается с ними\./gu, 'Усиление применяет только цену и эффекты двухручной версии, указанные в карточке заклинания.')
  .replace(/Рабочая редакция магии[^.]*\.\s*/gu, '')
  .replace(/Редакция атак, развития и магии · 12 октября/gu, 'Общие правила боя, развития и магии')
  .replace(/^Новая редакция$/u, 'Общие правила')
  .replace(/(?:Для|В|в) рабочей редакции\s*/gu, '')
  .replace(/Предлагаемая редакция:\s*/gu, '')
  .replace(/Предлагаемая перебалансировка:\s*/gu, '')
  .replace(/Предлагаемое уточнение движения/gu, 'Уточнение движения')
  .replace(/Предлагаемые двухручные версии/gu, 'Двухручные версии')
  .replace(/Предлагаем(?:ая|ый|ое|ые|ую|ой)\s+/gu, '')
  .replace(/предлагаем(?:ая|ый|ое|ые|ую|ой)\s+/gu, '')
  .replace(/(?:Новая |Предлагаемая )?[Рр]абочая карточка/gu, 'Условия')
  .replace(/Предложенная скорость/gu, 'Скорость')
  .replace(/Предложенный знак/gu, 'Знак')
  .replace(/Предлагаемая замена/gu, 'Правило')
  .replace(/Предложение для Пармы/gu, 'В Парме')
  .replace(/ - предложение(?=\s*$)/gmu, '')
  .replace(/ · черновик/gu, '')
  .replace(/ · книга \d+/gu, '')
  .replace(/Что меняется в общей механике атак/gu, 'Общая механика атак')
  .replace(/ — книжная ступень пока сохранена| — пока сохранена книжная ступень| — книжные значения пока сохранены/gu, '')
  .replace(/в предлагаемой системе\s*/gu, '')
  .replace(/;?\s*это предложение, а не /gu, '; это не ')
  .replace(/;?\s*это предлагаемое новое хозяйственное объединение/gu, '')
  .replace(/Это заменяет прежние предложения[^.]*\.\s*/gu, '')
  .replace(/\n{3,}/gu, '\n\n').trim();
}

export function playerTable(rows: string[][]): string[][] {
 if (!rows.length) return rows;
 const omitted=rows[0].flatMap((header,index)=> /^(Источник|Основание|Редакторская заметка|Статус согласования)$/u.test(header.trim()) || (header.trim()==='Статус' && rows.slice(1).some(row=>/Согласовано отдельно|Записано в общий черновик/u.test(row[index]??''))) ? [index] : []);
 return rows.map(row=>row.filter((_,i)=>!omitted.includes(i)).map(playerText)).filter(row=>row.some(Boolean));
}
